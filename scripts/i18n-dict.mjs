#!/usr/bin/env node
/* Regenerate startos/i18n/dictionaries/default.ts from the i18n() calls.
 *
 * IDS ARE STABLE. translations.ts maps id -> foreign string, so reassigning
 * an id silently mistranslates that message and nothing typechecks it. This
 * generator therefore READS the existing dictionary, keeps every id it finds,
 * and only appends new keys at the next free number. A generator that sorted
 * keys and renumbered would reshuffle every translation the first time a
 * source file was added.
 *
 * A key that disappears from the code keeps its id and is reported, not
 * deleted: removing it would free the id for reuse by a later key, which is
 * the same mistranslation by a slower route. Prune by hand, in both files,
 * deliberately.
 *
 *   node scripts/i18n-dict.mjs          # rewrite default.ts
 *   node scripts/i18n-dict.mjs --check  # fail if it would change (for CI)
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join, relative } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const SRC = join(ROOT, 'startos')
const DICT = join(SRC, 'i18n/dictionaries/default.ts')

const files = []
;(function walk(dir) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e)
    if (statSync(p).isDirectory()) {
      if (!p.includes('dictionaries')) walk(p)
    } else if (p.endsWith('.ts')) files.push(p)
  }
})(SRC)
files.sort()

/* Matches i18n('...') and i18n("..."), including the multi-line form prettier
   produces. The body allows escapes and stops at the matching unescaped
   quote. Template literals are deliberately NOT matched: an interpolated key
   cannot be looked up, and failing loudly here beats a missing translation. */
const CALL = /i18n\(\s*(['"])((?:\\.|(?!\1)[^\\])*)\1/gs
const found = new Map() // runtime string -> first file it came from
for (const f of files) {
  const src = readFileSync(f, 'utf8')
  for (const m of src.matchAll(CALL)) {
    // The capture is a JS string literal body; evaluate it to the value the
    // code will actually pass at runtime, which is what the key must be.
    const value = Function(`"use strict"; return ${m[1]}${m[2]}${m[1]}`)()
    if (!found.has(value)) found.set(value, relative(ROOT, f))
  }
}

const prevSrc = readFileSync(DICT, 'utf8')
const prev = new Map()
for (const m of prevSrc.matchAll(
  /^\s*(?:'((?:\\.|[^'\\])*)'|"((?:\\.|[^"\\])*)"|([A-Za-z_$][\w$]*)):\s*(\d+),$/gm,
)) {
  const lit =
    m[1] !== undefined ? `'${m[1]}'` : m[2] !== undefined ? `"${m[2]}"` : null
  const key = lit ? Function(`"use strict"; return ${lit}`)() : m[3]
  prev.set(key, Number(m[4]))
}

let next = prev.size ? Math.max(...prev.values()) + 1 : 0
const ids = new Map()
for (const [key] of found) ids.set(key, prev.has(key) ? prev.get(key) : next++)
// Keys that left the code keep their ids reserved.
const orphans = [...prev.keys()].filter((k) => !found.has(k))
for (const k of orphans) ids.set(k, prev.get(k))

/* Match prettier's own choice, so a regenerate never shows up as pure
   quote churn in the diff: bare key where legal, double quotes when the
   string contains an apostrophe and no double quote, single otherwise. */
const quote = (k) => {
  if (/^[A-Za-z_$][\w$]*$/.test(k)) return k
  const esc = (q) =>
    q +
    k
      .replace(/\\/g, '\\\\')
      .replace(new RegExp(q, 'g'), '\\' + q)
      .replace(/\n/g, '\\n') +
    q
  return k.includes("'") && !k.includes('"') ? esc('"') : esc("'")
}

const body = [...ids.entries()]
  .sort((a, b) => a[1] - b[1])
  .map(([k, id]) => `  ${quote(k)}: ${id},`)
  .join('\n')

const out = `export const DEFAULT_LANG = 'en_US'

/* Ids are STABLE and must never be renumbered: translations.ts maps id to
 * foreign string, so reassigning an id silently mistranslates that message.
 * Generated by scripts/i18n-dict.mjs from the i18n() calls in the code —
 * regenerate, do not edit. */
const dict = {
${body}
} as const

/**
 * Plumbing. DO NOT EDIT.
 */
export type I18nKey = keyof typeof dict
export type LangDict = Record<(typeof dict)[I18nKey], string>
export default dict
`

if (process.argv.includes('--check')) {
  if (out !== prevSrc) {
    console.error('default.ts is out of date — run: node scripts/i18n-dict.mjs')
    process.exit(1)
  }
  console.log(`i18n dictionary up to date (${ids.size} keys).`)
} else {
  writeFileSync(DICT, out)
  const added = [...found.keys()].filter((k) => !prev.has(k))
  console.log(`wrote ${ids.size} keys to ${relative(ROOT, DICT)}`)
  if (added.length)
    console.log(
      `  added ${added.length}: ${added.map((k) => JSON.stringify(k.slice(0, 48))).join(', ')}`,
    )
  if (orphans.length)
    console.log(
      `  no longer in the code (ids kept reserved): ${orphans.map((k) => JSON.stringify(k.slice(0, 40))).join(', ')}`,
    )
}
